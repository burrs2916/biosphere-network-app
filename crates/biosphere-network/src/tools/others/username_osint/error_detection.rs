use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CheckError {
    pub error_type: String,
    pub description: String,
    pub is_permanent: bool,
    pub solution: Option<String>,
}

impl CheckError {
    pub fn new(error_type: &str, description: &str) -> Self {
        let is_permanent = !TEMPORARY_ERROR_TYPES.contains(&error_type);
        let solution = ERROR_SOLUTIONS.get(error_type).map(|s| s.to_string());
        Self {
            error_type: error_type.to_string(),
            description: description.to_string(),
            is_permanent,
            solution,
        }
    }

    pub fn captcha(description: &str) -> Self {
        Self::new("Captcha", description)
    }

    pub fn bot_protection(description: &str) -> Self {
        Self::new("Bot protection", description)
    }

    pub fn censorship(description: &str) -> Self {
        Self::new("Censorship", description)
    }

    pub fn site_specific(description: &str) -> Self {
        Self::new("Site-specific", description)
    }

    pub fn access_denied(description: &str) -> Self {
        Self::new("Access denied", description)
    }

    pub fn request_blocked(description: &str) -> Self {
        Self::new("Request blocked", description)
    }
}

