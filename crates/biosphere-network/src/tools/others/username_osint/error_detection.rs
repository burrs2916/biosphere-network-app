const TEMPORARY_ERROR_TYPES: &[&str] = &[
    "Request timeout",
    "Unknown",
    "Request failed",
    "Connecting failure",
    "HTTP",
    "Proxy",
    "Interrupted",
    "Connection lost",
];

const ERROR_THRESHOLD_PERCENT: f64 = 3.0;

pub fn detect_common_errors(html: &str) -> Option<CheckError> {
    for pattern in get_common_error_patterns() {
        if html.contains(pattern.pattern) {
            return Some(pattern.error);
        }
    }
    None
}

pub fn detect_site_errors(html: &str, site_errors: &HashMap<String, String>) -> Option<CheckError> {
    for (flag, msg) in site_errors {
        if html.contains(flag) {
            return Some(CheckError::site_specific(msg));
        }
    }
    None
}

pub fn detect_error_page(
    html: &str,
    status_code: u16,
    site_errors: &HashMap<String, String>,
    ignore_403: bool,
) -> Option<CheckError> {
    if let Some(err) = detect_site_errors(html, site_errors) {
        return Some(err);
    }

    if let Some(err) = detect_common_errors(html) {
        return Some(err);
    }

    if status_code == 403 && !ignore_403 {
        return Some(CheckError::access_denied("403 status code, use proxy/VPN"));
    }

    if status_code == 999 {
        return None;
    }

    if status_code >= 500 {
        return Some(CheckError::new("Server", &format!("{} status code", status_code)));
    }

    None
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ErrorStats {
    pub error_type: String,
    pub count: usize,
    pub percentage: f64,
    pub is_important: bool,
    pub solution: Option<String>,
}

pub fn extract_and_group_errors(results: &[super::config::PlatformResult]) -> Vec<ErrorStats> {
    let mut error_counts: HashMap<String, usize> = HashMap::new();
    let total = results.len().max(1);

    for r in results {
        if let Some(ref et) = r.error_type {
            *error_counts.entry(et.clone()).or_insert(0) += 1;
        } else if r.error.is_some() {
            *error_counts.entry("Unknown".to_string()).or_insert(0) += 1;
        }
    }

    let mut stats: Vec<ErrorStats> = error_counts
        .into_iter()
        .map(|(err, count)| {
            let percentage = (count as f64 / total as f64) * 100.0;
            let is_important = percentage >= ERROR_THRESHOLD_PERCENT;
            let solution = ERROR_SOLUTIONS.get(err.as_str()).map(|s| s.to_string());
            ErrorStats {
                error_type: err,
                count,
                percentage,
                is_important,
                solution,
            }
        })
        .collect();

    stats.sort_by(|a, b| b.count.cmp(&a.count));
    stats
}
